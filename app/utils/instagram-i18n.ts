const STRINGS: Record<string, Partial<InstagramStrings>> = { en, es, it, de, fr };

export function getInstagramTranslations(language: string): InstagramStrings {
  const lang = language === "auto" ? "en" : language;
  return { ...en, ...(STRINGS[lang] ?? {}) };
}

export function useInstagramT(): InstagramStrings & { lang: string } {
  const data = useRouteLoaderData("routes/app") as { language?: string } | undefined;
  const lang = !data?.language || data.language === "auto" ? "en" : data.language;
  // Stable identity per language — pages use it in effect dependency lists.
  return useMemo(() => ({ ...getInstagramTranslations(lang), lang }), [lang]);
}

/** Replace {placeholders} in a translated string. */
export function fmt(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (match, key) => (key in values ? String(values[key]) : match));
}
